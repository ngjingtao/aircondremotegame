/* ═══════════════════════════════════════════
   Electricity — the picture

   One circuit. Each step lights the part it is about and closes the
   switch once the lesson reaches it, so the current visibly starts.
   ═══════════════════════════════════════════ */
window.ARG = window.ARG || {};

ARG.scene = (function () {

  const $ = id => document.getElementById(id);
  let root = null;

  function build() {
    root = $('art');
  }

  function show(i) {
    const list = ARG.sim.STEPS;
    const n = Math.max(0, Math.min(list.length - 1, i));
    const step = list[n];
    if (!step) return;

    if (!root) root = $('art');
    if (root) {
      /* the switch is closed from step 3, the bulb lights from step 4 */
      root.classList.toggle('live', n >= 2);
      root.classList.toggle('lit', n >= 3);
      root.classList.toggle('warn', n === 5);

      const parts = root.querySelectorAll('[data-lab]');
      Array.prototype.forEach.call(parts, p => {
        const labs = String(p.dataset.lab || '').split(/\s+/);
        p.classList.toggle('on', labs.indexOf(step.scene) >= 0);
      });
    }

    if (ARG.art) ARG.art.show('electric', n);
    const status = $('scene-status');
    if (status) status.textContent = ARG.i18n.t(step.title);
    const note = $('pane-note');
    if (note) note.textContent = ARG.i18n.t('note');
  }

  return { build, show };
})();
